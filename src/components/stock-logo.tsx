interface StockLogoProps {
  symbol: string;
  size?: number;
  className?: string;
}

/** Renders an inline SVG brand logo for a watchlist symbol. */
export function StockLogo({ symbol, size = 32, className }: StockLogoProps) {
  const logo = LOGOS[symbol];
  if (!logo) {
    // Fallback: colored circle with first letter of underlying
    const fallbackColors: Record<string, string> = {
      rNVDA: "#76b900",
      rTSLA: "#cc0000",
      rAAPL: "#555555",
      rCOIN: "#0052ff",
      rMSTR: "#f7931a",
    };
    const color = fallbackColors[symbol] || "#485346";
    const initial = symbol.replace("r", "").charAt(0);
    return (
      <div
        className={className}
        style={{
          width: size,
          height: size,
          backgroundColor: color,
          borderRadius: "50%",
          display: "flex",
          alignItems: "center",
          justifyContent: "center",
          color: "white",
          fontSize: size * 0.35,
          fontWeight: 500,
        }}
        aria-hidden="true"
      >
        {initial}
      </div>
    );
  }

  return (
    <svg
      role="img"
      viewBox="0 0 24 24"
      width={size}
      height={size}
      className={className}
      fill={logo.hex}
      aria-label={`${symbol} logo`}
    >
      <path d={logo.path} />
    </svg>
  );
}
